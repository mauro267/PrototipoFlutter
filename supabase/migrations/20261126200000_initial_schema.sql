-- Esquema inicial de RutaViva, a partir de docs/modelo.md (MR_RutaViva.pdf, Caso 4).
-- Nombres del modelo: español, singular y llaves numéricas (spine AD-08).

create table public.zona (
  id_zona bigint generated by default as identity primary key,
  nombre text not null unique,
  ciudad text not null,
  pais text not null
);

create table public.usuario (
  id_usuario bigint generated by default as identity primary key,
  auth_uuid uuid not null unique references auth.users(id) on delete cascade,
  nombre text not null,
  email text not null unique,
  rol text not null default 'coordinador' check (rol in ('coordinador', 'mecanico')),
  pais text not null default 'Colombia',
  activo boolean not null default true
);

create table public.conductor (
  id_conductor bigint generated by default as identity primary key,
  nombre text not null,
  documento text not null unique,
  telefono text,
  licencia text not null,
  id_zona bigint not null references public.zona(id_zona),
  activo boolean not null default true
);

create table public.vehiculo (
  id_vehiculo bigint generated by default as identity primary key,
  placa text not null unique,
  tipo text not null check (tipo in ('furgon', 'moto', 'camion', 'tractocamion')),
  marca text not null,
  modelo text not null,
  id_zona bigint not null references public.zona(id_zona),
  estado_operativo text not null default 'disponible'
    check (estado_operativo in ('en_ruta', 'disponible', 'alerta', 'varado', 'mantenimiento')),
  kilometraje_actual numeric not null default 0 check (kilometraje_actual >= 0),
  has_telemetry boolean not null default false,
  fecha_instalacion_iot date,
  intervalo_preventivo_km numeric not null check (intervalo_preventivo_km > 0),
  km_ultimo_preventivo numeric not null default 0 check (km_ultimo_preventivo >= 0),
  check (not has_telemetry or fecha_instalacion_iot is not null)
);

create table public.asignacion_turno (
  id_asignacion bigint generated by default as identity primary key,
  id_conductor bigint not null references public.conductor(id_conductor),
  id_vehiculo bigint not null references public.vehiculo(id_vehiculo),
  fecha date not null,
  hora_inicio timestamptz,
  hora_fin timestamptz,
  check (hora_fin is null or hora_inicio is null or hora_fin >= hora_inicio)
);

create table public.viaje (
  id_viaje bigint generated by default as identity primary key,
  codigo text not null unique,
  id_asignacion bigint not null references public.asignacion_turno(id_asignacion),
  fecha_inicio timestamptz not null,
  fecha_fin timestamptz,
  km_recorridos numeric not null default 0 check (km_recorridos >= 0),
  paradas_totales integer not null default 0 check (paradas_totales >= 0),
  paradas_completadas integer not null default 0
    check (paradas_completadas >= 0 and paradas_completadas <= paradas_totales),
  estado text not null default 'en_curso' check (estado in ('en_curso', 'completado'))
);

create table public.evento_conduccion (
  id_evento bigint generated by default as identity primary key,
  id_vehiculo bigint not null references public.vehiculo(id_vehiculo),
  id_viaje bigint references public.viaje(id_viaje),
  fecha_hora timestamptz not null,
  tipo text not null,
  magnitud double precision not null,
  unidad text not null,
  ubicacion text
);

create table public.telemetria_gps (
  id_lectura bigint generated by default as identity primary key,
  id_vehiculo bigint not null references public.vehiculo(id_vehiculo),
  fecha_hora timestamptz not null,
  lat double precision not null check (lat between -90 and 90),
  lon double precision not null check (lon between -180 and 180),
  velocidad double precision not null check (velocidad >= 0)
);

create table public.telemetria_obd (
  id_lectura bigint generated by default as identity primary key,
  id_vehiculo bigint not null references public.vehiculo(id_vehiculo),
  fecha_hora timestamptz not null,
  codigo_falla text,
  temp_motor double precision not null,
  rpm double precision not null check (rpm >= 0),
  nivel_combustible double precision not null check (nivel_combustible between 0 and 100)
);

create table public.prediccion_falla (
  id_prediccion bigint generated by default as identity primary key,
  id_vehiculo bigint not null references public.vehiculo(id_vehiculo),
  fecha_prediccion date not null,
  componente text not null,
  probabilidad double precision not null check (probabilidad between 0 and 1),
  fecha_limite_mantenimiento date not null,
  estado text not null default 'pendiente'
    check (estado in ('pendiente', 'programada', 'confirmada', 'descartada')),
  fecha_programada date,
  id_usuario_revision bigint references public.usuario(id_usuario) on delete set null,
  check (estado <> 'programada' or fecha_programada is not null)
);

create table public.mantenimiento (
  id_mantenimiento bigint generated by default as identity primary key,
  id_vehiculo bigint not null references public.vehiculo(id_vehiculo),
  id_prediccion bigint references public.prediccion_falla(id_prediccion) on delete set null,
  fecha date not null default current_date,
  origen text not null check (origen in ('preventivo', 'correctivo')),
  tipo_falla text not null,
  descripcion text not null default '',
  kilometraje numeric not null check (kilometraje >= 0),
  costo numeric not null check (costo >= 0),
  moneda text not null default 'COP',
  horas_fuera_servicio numeric not null check (horas_fuera_servicio >= 0),
  en_ruta boolean not null default false,
  id_usuario_registro bigint references public.usuario(id_usuario) on delete set null,
  check (origen = 'correctivo' or not en_ruta)
);

create table public.evidencia_mantenimiento (
  id_evidencia bigint generated by default as identity primary key,
  id_mantenimiento bigint not null references public.mantenimiento(id_mantenimiento) on delete cascade,
  ruta text not null unique,
  url text not null,
  fecha_subida timestamptz not null default now(),
  auth_uuid_subida uuid references auth.users(id) on delete set null
);

create table public.cliente_retailer (
  id_cliente bigint generated by default as identity primary key,
  nombre text not null unique,
  pais text not null,
  canal_integracion text not null,
  formato_origen text not null
);

create table public.orden_entrega (
  id_orden bigint generated by default as identity primary key,
  codigo text not null unique,
  id_cliente bigint not null references public.cliente_retailer(id_cliente),
  id_viaje bigint references public.viaje(id_viaje),
  direccion_destino text not null,
  ciudad text not null,
  fecha_creacion timestamptz not null default now(),
  fecha_promesa timestamptz not null,
  fecha_entrega_real timestamptz,
  estado text not null default 'pendiente'
    check (estado in ('a_tiempo', 'en_camino', 'en_riesgo', 'retrasada', 'pendiente'))
);

create table public.parametro (
  clave text primary key,
  valor numeric not null
);

create index on public.vehiculo (id_zona);
create index on public.telemetria_gps (id_vehiculo, fecha_hora desc);
create index on public.telemetria_obd (id_vehiculo, fecha_hora desc);
create index on public.evento_conduccion (id_vehiculo, fecha_hora desc);
create index on public.mantenimiento (id_vehiculo);
create index on public.evidencia_mantenimiento (id_mantenimiento);
create index on public.orden_entrega (id_cliente, estado);

grant select, insert, update, delete on
  public.zona, public.usuario, public.conductor, public.vehiculo,
  public.asignacion_turno, public.viaje, public.evento_conduccion,
  public.telemetria_gps, public.telemetria_obd, public.prediccion_falla,
  public.mantenimiento, public.evidencia_mantenimiento, public.cliente_retailer,
  public.orden_entrega, public.parametro
  to anon, authenticated;

grant usage, select on all sequences in schema public to anon, authenticated;
